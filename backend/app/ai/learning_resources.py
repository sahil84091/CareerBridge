def get_curated_resources_for_skills(skill_names: List[str]) -> List[Dict[str, Any]]:
    """Returns curated high-quality video resources for a list of skill names."""
    results = []
    seen_titles = set()

    for raw_skill in skill_names:
        norm = raw_skill.strip().lower()
        # Direct lookup or substring lookup
        found = None
        for key, res_list in CURATED_SKILL_RESOURCES.items():
            if key in norm or norm in key:
                found = res_list
                break

        if found:
            for item in found:
                if item["title"] not in seen_titles:
                    seen_titles.add(item["title"])
                    results.append(item)
        else:
            # Fallback smart learning reference
            clean_name = raw_skill.strip()
            title = f"{clean_name} Full Course & Hands-on Masterclass"
            if title not in seen_titles:
                seen_titles.add(title)
                query_slug = clean_name.replace(" ", "+")
                results.append({
                    "title": title,
                    "platform": "YouTube / freeCodeCamp & Community",
                    "url": f"https://www.youtube.com/results?search_query={query_slug}+tutorial+full+course",
                    "duration": "3h+",
                    "type": "video",
                    "skill": clean_name,
                    "description": f"Curated technical video walkthrough and real-world project tutorial for {clean_name}.",
                })

    return results


def build_structured_plan(priority_skills: List[str], role_title: str) -> List[Dict[str, Any]]:
    """Generates an action-oriented structured sprint plan with video recommendations."""
    if not priority_skills:
        return []

    phases = [
        ("Foundation & Core Paradigms", "2–3 Weeks", "Master foundational syntax, design patterns, and core developer tools."),
        ("Hands-on Engineering & Systems", "3–4 Weeks", "Build end-to-end features, API integrations, and practical implementations."),
        ("Enterprise Architecture & Testing", "2–3 Weeks", "Implement production error handling, testing suites, and optimization."),
        ("Portfolio Capstone & Deployment", "2 Weeks", "Deploy full production application and document real-world architectural decisions."),
    ]

    steps = []
    chunk_size = max(1, len(priority_skills) // min(4, len(priority_skills)))

    for idx, (phase_name, duration, desc) in enumerate(phases):
        start_i = idx * chunk_size
        end_i = start_i + chunk_size if idx < len(phases) - 1 else len(priority_skills)
        focus = priority_skills[start_i:end_i] if start_i < len(priority_skills) else [priority_skills[-1]]

        resources = get_curated_resources_for_skills(focus)
        recommended_video = resources[0] if resources else None

        steps.append({
            "step_number": idx + 1,
            "phase_name": phase_name,
            "title": f"Master {', '.join(focus[:2])} for {role_title}",
            "focus_skills": focus,
            "estimated_weeks": duration,
            "action_items": [
                f"Complete guided video walkthrough on {focus[0]}.",
                f"Build a standalone micro-project demonstrating {focus[0]} fundamentals.",
                desc,
            ],
            "recommended_video": recommended_video,
        })

    return steps
